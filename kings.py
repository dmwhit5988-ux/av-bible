"""The kings of Israel and Judah, with the judges before them and the foreign
kings the histories name: for the Kings and prophets reference page
(generate_kings_reference.py) and the verse pictures to come.

Two chronologies, never mixed:

- **Ussher** is the house count, as on the OT family tree and timeline: his
  years are `chronology.BIND`'s reigns, read here by `ussher_years` and
  never typed twice. Three reigns BIND doesn't hold have their own, each
  with its source in `ussher_note`: David's (Hebron 1055, all Israel 1048,
  died 1015), Ish-bosheth's, and Tibni's (derived from the text).
- **Thiele** (The Mysterious Numbers of the Hebrew Kings, 1983) is the
  modern synchronised count, here in whole years as the Thiele column of
  Wikipedia's "Kings of Israel and Judah" table gives it (read 2026-10-28).
  Thiele dates no reign before the division but Solomon's (971/970-931/930,
  from the forty years back from 931/930); Saul's and David's are left out.
  `coregent` is the year a king's own article says Thiele starts a
  coregency, where it does; Thiele's chart writes most years split across
  two calendar years (931/930), which the whole years round.

Each reign has the WEB's own words, each with its verse, checked against
the text: the father and mother, the accession formula, the length, the
verdict, how the reign ended and where he was buried, and the passages in
Samuel or Kings and in Chronicles. Where the text gives two figures
(`length_alt`) both are kept, not reconciled.

EVENTS are the foreign kings' dealings with Israel and Judah, each dated by
the Israelite or Judahite king's regnal year the text gives (`anchor_year`:
a number, "accession", "death", or "during" where it gives none), so each
chronology places them by its own count; `modern` is the event's date in
the usual modern reckoning, with its source, for the card.

JUDGES are the deliverers of Judges and 1 Samuel with the years the text
gives each. Their sum, with the oppressions, exceeds the 480 years of
1 Kings 6:1, so they are drawn in order, not on the year line.
"""

