def crown_rings(t0, stagger=.07, dur=1.0, until=None):
    """One pulse of the outline of each fruit in the crown, the low ones aside, in a wave west to
    east. The drawing of the fruit stays. `until`: the last of them ends then."""
    kx, ky = KNOW
    spots = G.knowledge_fruit_spots()
    idx = sorted(range(6, len(spots)), key=lambda i: spots[i][0])
    if until is not None:
        stagger = (until - dur - t0) / max(1, len(idx) - 1)
    o = ""
    for n, i in enumerate(idx):
        fx, fy = spots[i]
        o += (f'<circle cx="{kx + fx * PXU:.1f}" cy="{ky - fy * PXU + 9:.1f}" r="10.5" fill="none" '
              f'stroke="{C.rgb(HL)}" stroke-width="2.4" opacity="0">'
              '<animate attributeName="opacity" values="0;1;1;0" keyTimes="0;.25;.6;1" '
              f'begin="{t0 + n * stagger:.2f}s" dur="{dur:.2f}s" fill="freeze"/></circle>')
    return o


def matched(at, shot):
    """3:6: where on the fruit's plate, from where it hangs, the fruit is on the screen where `shot`
    shows it with its stem's top at `at`, but never so low that the plate's frame cuts it. Its size
    changes across the cut; its place doesn't."""
    px, py, pz = SHOTS["fruit"]
    x, y, z = SHOTS[shot]
    mid = FRUIT_C[1] - FRUIT_Y
    lowest = py + C.H / 2 / pz - FRUIT_CLEAR
    return (px + (at[0] - x) * z / pz - FRUIT_X,
            min(py + (at[1] + mid - y) * z / pz, lowest) - mid - FRUIT_Y)


def foot_svg(heel0, heel1=None, t=None):
    """3:15's one foot in stone, at the heel's plate: its calf, five toes, an ankle bone. With `t`,
    the heel lifts from heel0 to heel1."""
    def shape(heel):
        parts = F.foot(heel, s=PXU)
        return (G._d([(x, -y) for x, y in parts[0][1]]),
                poly_d([(x, -y) for x, y in parts[-1][1]]))
    fill, ink = G._hex(STONE_SKIN), G._hex(STONE_INK)
    d0, a0 = shape(heel0)
    an1 = an2 = ""
    if heel1 is not None:
        d1, a1 = shape(heel1)
        timing = (f'begin="{t:.2f}s" dur="0.35s" fill="freeze" calcMode="spline" keyTimes="0;1" '
                  'keySplines=".2 .7 .3 1"')
        an1 = f'<animate attributeName="d" values="{d0};{d1}" {timing}/>'
        an2 = f'<animate attributeName="d" values="{a0};{a1}" {timing}/>'
    toes = "".join(f'<ellipse cx="{x}" cy="{-y}" rx="{r * 1.12:.2f}" ry="{r}" fill="{fill}" '
                   f'stroke="{ink}" stroke-width=".3"/>' for x, y, r in F.foot_toes(PXU)[::-1])
