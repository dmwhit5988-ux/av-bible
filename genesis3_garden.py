def crowd(fl, t=None, go=None):
    """The ten of the living: their own drawing in the live paint, small and far off, standing up
    one by one from t. From `go` they turn and walk off east, at the one pace as far off as they
    are, a stride for as long as they walk; each is gone once the frame has lost it."""
    east = {"m": (False, 1), "w": (True, 1)}
    o = stone_defs(fl, "e", {"m": (False, -1), "w": (True, -1)}, paint="live")
    if go is None:
        for i, (x, d, k, kind) in enumerate(LIVING):
            o += stone_use(fl, "e" + kind, x, G.land_y(x, d), None if t is None else t + .06 * i,
                           k=k, who="the living")
        return o
    o += (stone_defs(fl, "ea", east, "live", "swing", "walk")
          + stone_defs(fl, "eb", east, "live", "swing2", "walk2"))
    # how far behind them the stride reaches, px at life
    rear = {kind: PXU * min(p[0] for part, pts, _m in F.side_person(woman, "swing", "walk")
                            if part == "fill" for p in pts) for kind, (woman, _f) in east.items()}
    grid = [go + i * .02 for i in range(int((fl.dur - go) / .02) + 1)]
    for x, d, k, kind in LIVING:
        y, pace = G.land_y(x, d), WALK_V * k
        t_off = next(round(q, 2) for q in grid
                     if x + k * rear[kind] + pace * (q - go) > C.visible_world(fl.at(q))[2])
        dx = pace * (t_off - go)
        drawn_figure(fl, "the living", x, x + dx, y, k, None, t_off)
        n = max(1, round((t_off - go) / .5))
        each = (f'dur="{(t_off - go) / n:.3f}s" begin="{go:.2f}s" repeatCount="{n}" '
                'calcMode="discrete" fill="freeze"')
        o += (f'<g transform="translate({x} {y:.1f})"><g>'
              '<animateTransform attributeName="transform" type="translate" '
              f'values="0 0;{dx:.1f} {G.land_y(x + dx, d) - y:.1f}" begin="{go:.2f}s" '
              f'dur="{t_off - go:.2f}s" fill="freeze"/>'
              f'<set attributeName="visibility" to="hidden" begin="{t_off:.2f}s"/>'
              f'<g transform="scale({k})"><g><set attributeName="visibility" to="hidden" '
              f'begin="{go:.2f}s"/><use href="#e{kind}"/></g>'
              f'<g visibility="hidden"><set attributeName="visibility" to="visible" '
              f'begin="{go:.2f}s"/><g><animate attributeName="visibility" values="visible;hidden" '
              f'keyTimes="0;.5" {each}/><use href="#ea{kind}"/></g><g visibility="hidden">'
              f'<animate attributeName="visibility" values="hidden;visible" keyTimes="0;.5" '
              f'{each}/><use href="#eb{kind}"/></g></g></g></g></g>')
    return o


