def slit_d(open_by):
    """The line on his side as a closed shape, its two lips `open_by` either side of the middle."""
    (ax, ay), (bx, by) = SLIT
    L = math.hypot(bx - ax, by - ay)
    nx, ny = (by - ay) / L * open_by, -(bx - ax) / L * open_by
    mx, my = (ax + bx) / 2, (ay + by) / 2
    return (f"M{ax:.2f} {ay:.2f}Q{mx + nx:.2f} {my + ny:.2f} {bx:.2f} {by:.2f}"
            f"Q{mx - nx:.2f} {my - ny:.2f} {ax:.2f} {ay:.2f}Z")


