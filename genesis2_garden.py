def river_sweeping(x_from, x_to, begin, dur):
    """The river as it comes down its course: the dry bed under, the water over it, opened by a rect
    running east in one animation, as a head does on the plan. It sets off at a run, so that its
    water is down out of the heights while "out of Eden" is said, and slows as it nears the
    parting."""
    wet = G.river_svg((begin, dur + 2.0), ("near", "mid", "far", "heads"))
    dry = G.dry_course_svg()
    out = {}
    for k, svg in wet.items():
        cid = f"rs{k}"
        out[k] = (dry[k]
                  + f'<defs><clipPath id="{cid}">'
                  f'<rect x="{x_from}" y="-3000" width="1" height="9000">'
                  f'<animate attributeName="width" values="1;{x_to - x_from}" begin="{begin:g}s" '
                  f'dur="{dur:g}s" fill="freeze" calcMode="spline" keyTimes="0;1" '
                  f'keySplines=".2 .4 .6 1"/></rect></clipPath></defs>'
                  f'<g clip-path="url(#{cid})">{svg}</g>')
    return out


