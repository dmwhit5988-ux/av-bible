def head_svg(p, name, sweep=None):
    """One head of the river. `sweep` = (x_from, begin, dur) runs it out, by a clip."""
    g = G._rounded(p["heads"][name])
    if not sweep:
        return g
    x0 = G.PARTING[0] - 300
    cid = "ph" + name[0]
    x_from, b, d = sweep
    an = (f'<animate attributeName="width" values="{x_from - x0};{HEAD_FULL - x0}" begin="{b:g}s" '
          f'dur="{d:g}s" fill="freeze" calcMode="spline" keyTimes="0;1" keySplines=".3 0 .6 1"/>')
    return (f'<defs><clipPath id="{cid}"><rect x="{x0}" y="-7000" width="{x_from - x0}" '
            f'height="16000">{an}</rect></clipPath></defs><g clip-path="url(#{cid})">{g}</g>')


def plan_world(p, heads, lands="", fl=None):
    """The plan in paint order, the heads as given (name -> svg). `fl`: the Flight of a verse
    hung in it, whose garden and named crowns come in only as the side view goes (`plan_garden`)."""
    garden, named = p["garden"], p["named"]
    if fl is not None:
        garden, named = G.plan_garden(fl, garden), G.plan_garden(fl, named)
    return (f'<defs>{p["defs"]}</defs>'
            + G._rounded(p["land"] + lands + garden + p["river"] + "".join(heads.values())
                         + named))


def plan_verse(v, draw):
    """A verse on the plan alone. draw(p, run, fl): p is the still plan, `run` the same with its
    water running, for the verse's length, for the head that verse names."""
    v.plan_only = True
    v.plan = lambda fl: draw(plan_pieces(), plan_pieces(running_from(v, 0.0)), fl)


def running_from(v, t):
    """The water's run for a head named in verse v from t: to just before the verse ends."""
    return round(t, 2), round(v.dur - .2 - t, 2)


def heads_with(p, running):
    """All four heads, those in `running` ({name: the plan with its water running}) drawn last."""
    heads = {n: head_svg(p, n) for n in G.HEADS if n not in running}
    heads.update((n, head_svg(run, n)) for n, run in running.items())
    return heads


