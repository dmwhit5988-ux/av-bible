def ring_trace(pts, t, dur, w=6.0):
    """A pulse round an outline: traced, held a moment, and at rest it stays at the 0.6 floor. The
    highlight runs on a keyline of the names' dark ink, so that it reads on gold."""
    L = poly_len(pts + pts[:1])

    def line(col, width):
        return (f'<path d="{poly_d(pts + pts[:1])}" fill="none" stroke="{col}" '
                f'stroke-width="{width:g}" stroke-dasharray="{L:.0f} {L:.0f}" '
                f'stroke-dashoffset="{L:.0f}" stroke-linejoin="round">'
                f'<animate attributeName="stroke-dashoffset" values="{L:.0f};0" begin="{t:.2f}s" '
                f'dur="{dur:.2f}s" fill="freeze"/></path>')
    return (f'<g><animate attributeName="opacity" values="1;1;.6" keyTimes="0;.6;1" '
            f'begin="{t:.2f}s" dur="{dur + .8:.2f}s" fill="freeze"/>'
            f'{line(C.rgb(HALO), w + 3)}{line(C.rgb(HL), w)}</g>')


